export function t(lang, key, vars = {}) {
  const table = STRINGS[lang] || STRINGS.en;
  const str = table[key] ?? STRINGS.en[key] ?? key;
  return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}

export const name = (key, lang) => (NAMES[lang] || NAMES.en)[key] || key;

export function termsText(field, lang) {
  if (field.terms === 'free') return t(lang, 'termsFree');
  if (field.terms === 'manure') return t(lang, 'termsManure');
  if (field.terms === 'price') return t(lang, 'termsPrice', { price: money(field.price) });
  return '-';
}
